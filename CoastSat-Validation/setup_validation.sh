    cd "$ORIGINAL_DIR"
    BASELINE_COMMIT=$(git rev-parse "$BASELINE_COMMIT" 2>/dev/null || echo "$BASELINE_COMMIT")
    echo -e "${YELLOW}Resolved baseline commit: $BASELINE_COMMIT${NC}"
fi

