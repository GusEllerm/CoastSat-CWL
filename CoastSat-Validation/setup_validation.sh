    BASELINE_COMMIT=$(python3 -c "import json; print(json.load(open('$CONFIG_FILE')).get('baseline_commit', 'HEAD~1'))" 2>/dev/null || echo "HEAD~1")
    SITES=$(python3 -c "import json; print(' '.join(json.load(open('$CONFIG_FILE')).get('validation_sites', ['nzd0001', 'sar0001'])))" 2>/dev/null || echo "nzd0001 sar0001")
    echo "  Baseline commit: $BASELINE_COMMIT"
    echo "  Validation sites: $SITES"
else
    echo -e "${YELLOW}config.json not found, using defaults${NC}"
    BASELINE_COMMIT="HEAD~1"
    SITES="nzd0001 sar0001"
fi

# Parse arguments (override config if provided)
while [[ $# -gt 0 ]]; do
    case $1 in
        --baseline-commit)
            BASELINE_COMMIT="$2"
            echo -e "${YELLOW}Overriding baseline commit from command line: $BASELINE_COMMIT${NC}"
            shift 2
            ;;
        --sites)
            SITES="$2"
            echo -e "${YELLOW}Overriding sites from command line: $SITES${NC}"
            shift 2
            ;;
        --config)
            CONFIG_FILE="$2"
            echo -e "${YELLOW}Using config file: $CONFIG_FILE${NC}"
            shift 2
            ;;
        --help)
            echo "Usage: $0 [OPTIONS]"
            echo ""
            echo "Options:"
            echo "  --baseline-commit COMMIT   Git commit/tag to use as baseline (overrides config.json)"
            echo "  --sites SITES              Space-separated list of site IDs (overrides config.json)"
            echo "  --config FILE              Path to config.json file (default: ./config.json)"
            echo "  --help                     Show this help message"
            echo ""
            echo "Configuration:"
            echo "  Default configuration is loaded from config.json"
            echo "  Command-line options override config.json values"
            echo ""
            echo "Example:"
            echo "  $0 --baseline-commit HEAD~3 --sites 'nzd0001 sar0001'"
            exit 0
            ;;
        *)
            echo -e "${RED}Unknown option: $1${NC}"
            echo "Use --help for usage information"
            exit 1
            ;;
    esac
done

# Resolve baseline commit if it's a relative reference
