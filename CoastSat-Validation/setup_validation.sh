mkdir -p "$WORKFLOW_DIR"

# Extract baseline data
extract_from_commit "$BASELINE_COMMIT" "$BASELINE_DIR" "baseline data"

# Copy current data as validation
copy_current_data "$VALIDATION_DATA_DIR" "validation data"

# Copy workflow code
copy_workflow

echo -e "\n${GREEN}✓ Validation setup complete!${NC}"
echo ""
echo "Baseline data: $BASELINE_DIR"
echo "Validation data: $VALIDATION_DATA_DIR"
echo "Workflow code: $WORKFLOW_DIR"
echo ""
echo "Next steps:"
echo "  1. Review the extracted data"
echo "  2. Run the workflow from baseline to generate new results"
echo "  3. Compare generated results with validation data"

