#!/bin/bash
# Setup script for CoastSat validation framework
# This script extracts baseline data from a previous commit and validation data from current commit

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
VALIDATION_DIR="$SCRIPT_DIR"
BASELINE_DIR="$VALIDATION_DIR/baseline"
VALIDATION_DATA_DIR="$VALIDATION_DIR/validation"
WORKFLOW_DIR="$VALIDATION_DIR/workflow"
ORIGINAL_DIR="$SCRIPT_DIR/../CoastSat-Original"

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m' # No Color

echo -e "${GREEN}Setting up CoastSat Validation Framework${NC}"
echo "=============================================="

# Check if original directory exists
if [ ! -d "$ORIGINAL_DIR" ]; then
    echo -e "${RED}Error: CoastSat-Original directory not found at $ORIGINAL_DIR${NC}"
    exit 1
fi

# Function to extract data from a specific commit
extract_from_commit() {
    local commit=$1
    local target_dir=$2
    local description=$3
    
    echo -e "\n${YELLOW}Extracting $description from commit: $commit${NC}"
    
    cd "$ORIGINAL_DIR"
    
    # Check if commit exists
    if ! git rev-parse --verify "$commit" > /dev/null 2>&1; then
        echo -e "${RED}Error: Commit $commit not found${NC}"
        return 1
    fi
    
    # Get commit metadata
    local commit_hash=$(git rev-parse "$commit")
    local commit_date=$(git log -1 --format=%ci "$commit")
    local commit_date_iso=$(git log -1 --format=%cI "$commit")
    local commit_message=$(git log -1 --format=%s "$commit")
    local commit_author=$(git log -1 --format="%an <%ae>" "$commit")
    local commit_ref=$(git describe --tags --exact-match "$commit" 2>/dev/null || echo "N/A")
    local extraction_date=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
    
    # Create baseline metadata file
    echo "  - Creating baseline metadata..."
    cat > "$target_dir/BASELINE_INFO.md" << EOF
# Baseline Data Information

This directory contains baseline data extracted from the CoastSat-Original repository for validation purposes.

## Source Commit Information

- **Commit Hash**: \`$commit_hash\`
- **Commit Reference**: \`$commit\`
- **Git Tag** (if applicable): $commit_ref
- **Commit Date**: $commit_date ($commit_date_iso)
- **Commit Author**: $commit_author
- **Commit Message**: $commit_message

## Extraction Information

- **Extracted On**: $extraction_date
- **Extracted By**: \`$(whoami)\` on \`$(hostname)\`
- **Sites Included**: $SITES

## Data Contents

This baseline includes:
- \`transects_extended.geojson\`: Transect geometry and statistics from the baseline commit
- \`data/{site}/\`: Site-specific data files for each validation site

## Usage

This baseline data represents the starting state before running the workflow. The workflow should process new data incrementally from this point and produce results matching the validation dataset.

## Repository Information

- **Source Repository**: \`$ORIGINAL_DIR\`
- **Repository URL**: $(git remote get-url origin 2>/dev/null || echo "N/A")

---

*This file was automatically generated by \`setup_validation.sh\`*
EOF
    echo "    ✓ BASELINE_INFO.md created"
    
    # Extract transects_extended.geojson
    echo "  - Extracting transects_extended.geojson..."
    git show "$commit:transects_extended.geojson" > "$target_dir/transects_extended.geojson" 2>/dev/null || echo "    (file not found in this commit)"
    
    # Extract data files for specified sites
    if [ -n "$SITES" ]; then
        for site in $SITES; do
            echo "  - Extracting data for site: $site..."
            mkdir -p "$target_dir/data/$site"
            
            # Extract CSV files
            for file in transect_time_series.csv transect_time_series_tidally_corrected.csv tides.csv; do
                if git show "$commit:data/$site/$file" > "$target_dir/data/$site/$file" 2>/dev/null; then
                    echo "    ✓ $file"
                fi
            done
            
            # Extract XLSX file
            if git show "$commit:data/$site/$site.xlsx" > "$target_dir/data/$site/$site.xlsx" 2>/dev/null; then
                echo "    ✓ $site.xlsx"
            fi
        done
    fi
}

# Function to copy current data
copy_current_data() {
    local target_dir=$1
    local description=$2
    
    echo -e "\n${YELLOW}Copying $description from current state${NC}"
    
    cd "$ORIGINAL_DIR"
    
    # Get current commit metadata
    local commit_hash=$(git rev-parse HEAD)
    local commit_date=$(git log -1 --format=%ci HEAD)
    local commit_date_iso=$(git log -1 --format=%cI HEAD)
    local commit_message=$(git log -1 --format=%s HEAD)
    local commit_author=$(git log -1 --format="%an <%ae>" HEAD)
    local commit_ref=$(git describe --tags --exact-match HEAD 2>/dev/null || echo "N/A")
    local extraction_date=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
    
    # Create validation metadata file
    echo "  - Creating validation metadata..."
    cat > "$target_dir/VALIDATION_INFO.md" << EOF
# Validation Data Information

This directory contains validation data (expected results) from the current state of the CoastSat-Original repository.

## Source Commit Information

- **Commit Hash**: \`$commit_hash\`
- **Commit Date**: $commit_date ($commit_date_iso)
- **Commit Author**: $commit_author
- **Commit Message**: $commit_message
- **Git Tag** (if applicable): $commit_ref

## Extraction Information

- **Extracted On**: $extraction_date
- **Extracted By**: \`$(whoami)\` on \`$(hostname)\`
- **Sites Included**: $SITES

## Data Contents

This validation dataset includes:
- \`transects_extended.geojson\`: Current transect geometry and statistics
- \`data/{site}/\`: Current site-specific data files for each validation site

## Usage

This validation data represents the expected results after running the workflow from the baseline state. The workflow outputs should match these files when validation is successful.

## Repository Information

- **Source Repository**: \`$ORIGINAL_DIR\`
- **Repository URL**: $(git remote get-url origin 2>/dev/null || echo "N/A")

---

*This file was automatically generated by \`setup_validation.sh\`*
EOF
    echo "    ✓ VALIDATION_INFO.md created"
    
    # Copy transects_extended.geojson
    if [ -f "transects_extended.geojson" ]; then
        echo "  - Copying transects_extended.geojson..."
        cp "transects_extended.geojson" "$target_dir/"
    fi
    
    # Copy data files for specified sites
    if [ -n "$SITES" ]; then
        for site in $SITES; do
            if [ -d "data/$site" ]; then
                echo "  - Copying data for site: $site..."
                mkdir -p "$target_dir/data/$site"
                
                # Copy CSV files
                for file in transect_time_series.csv transect_time_series_tidally_corrected.csv tides.csv; do
                    if [ -f "data/$site/$file" ]; then
                        cp "data/$site/$file" "$target_dir/data/$site/"
                        echo "    ✓ $file"
                    fi
                done
                
                # Copy XLSX file
                if [ -f "data/$site/$site.xlsx" ]; then
                    cp "data/$site/$site.xlsx" "$target_dir/data/$site/"
                    echo "    ✓ $site.xlsx"
                fi
            fi
        done
    fi
}

# Function to copy workflow code
copy_workflow() {
    echo -e "\n${YELLOW}Copying workflow code${NC}"
    
    cd "$ORIGINAL_DIR"
    
    # List of files to copy
    FILES=(
        "batch_process_NZ.py"
        "batch_process_sar.py"
        "make_xlsx.py"
        "update.sh"
        "tidal_correction.ipynb"
        "slope_estimation.ipynb"
        "linear_models.ipynb"
        "polygons.geojson"
        "shorelines.geojson"
        "transects.geojson"
        "requirements.txt"
        "SDS_slope.py"
        "smoothn.py"
        ".gitignore"
    )
    
    # Copy patch_notebooks.py if it exists in validation directory
    if [ -f "$VALIDATION_DIR/workflow/patch_notebooks.py" ]; then
        cp "$VALIDATION_DIR/workflow/patch_notebooks.py" "$WORKFLOW_DIR/"
        chmod +x "$WORKFLOW_DIR/patch_notebooks.py"
        echo "  ✓ patch_notebooks.py (from validation directory)"
    fi
    
    # Copy config.json and scripts directory if they exist
    if [ -f "$VALIDATION_DIR/config.json" ]; then
        cp "$VALIDATION_DIR/config.json" "$WORKFLOW_DIR/../config.json" 2>/dev/null || true
    fi
    if [ -d "$VALIDATION_DIR/scripts" ]; then
        cp -r "$VALIDATION_DIR/scripts" "$WORKFLOW_DIR/../" 2>/dev/null || true
    fi
    
    for file in "${FILES[@]}"; do
        if [ -f "$file" ]; then
            cp "$file" "$WORKFLOW_DIR/"
            echo "  ✓ $file"
        fi
    done
    
    # Apply validation-specific fixes to batch processing scripts
    echo -e "\n${YELLOW}Applying validation-specific fixes...${NC}"
    apply_validation_fixes
    
    # Make scripts executable
    chmod +x "$WORKFLOW_DIR"/*.sh 2>/dev/null || true
    chmod +x "$WORKFLOW_DIR"/*.py 2>/dev/null || true
}

